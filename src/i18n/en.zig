//! English, and the type every language file fills: one field per user-visible string.
//! uk.zig, pl.zig, de.zig, es.zig, fr.zig each declare `pub const t: en.Strings = .{...}`, so a missing or extra
//! key is a compile error; strings.zig's test runs kit.i18n.check on every table (no empty string, the same
//! {N} placeholders as English, the plural forms the language needs). Access: `S.tr().key` (src/strings.zig).
//!
//! For translators:
//! - Keys are stable (tools/bugtest.ps1 reads them by name): never rename one, only change its text.
//! - "{0}".."{9}" are filled in at run time: keep every one, in any order ("{1} {0}" is fine).
//! - kit.i18n.Forms = a plural string: English/German/Spanish/French fill .one + .other (French .one = 0 and 1),
//!   Ukrainian/Polish fill .one + .few + .many.
//! - m* menu captions: '&' marks the Alt letter ("&File"); "&&" is a literal '&'.
//! - "…" (U+2026) at the end of a command means "opens a dialog"; dialog titles drop it automatically.
//! - Short labels: tb* (toolbar, under a 32 px icon: one or two short words), column headers (name..crc,
//!   pathColumn, extension, currentApp, property, value, fileColumn, location), buttons in dialogs
//!   (ok, cancel, browse, create, remove, renameButton, makeDefault, profileInMenuButton, saveProfile, moveUp,
//!   moveDown, copyButton, close, stop, locate, convertButton): buttons are 98-118 px at 100 % - about 12-14
//!   characters before the text is cut.
//! - French: U+00A0 (no-break space) before ? ! : ; and inside « ».
//! - Not translated anywhere: format names (7z, ZIP), CLI switches (-p, -y), paths, MakePack.
